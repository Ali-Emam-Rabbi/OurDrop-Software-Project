// File-type icon with a per-type tint (used in lists, staging and history).
export function FileTypeIcon({ name, size = 20 }: { name: string; size?: number }) {
  const ext = name.split(".").pop()?.toLowerCase() || "";
  let icon = "file";
  let color = "#7DB4FF";
  if (["jpg", "jpeg", "png", "gif", "webp", "bmp", "svg", "heic"].includes(ext)) {
    icon = "image";
    color = "#C084FC";
  } else if (["mp4", "mkv", "mov", "avi", "webm", "3gp"].includes(ext)) {
    icon = "video";
    color = "#F87171";
  } else if (["mp3", "wav", "flac", "aac", "ogg", "m4a"].includes(ext)) {
    icon = "audio";
    color = "#FBBF24";
  } else if (ext === "pdf") {
    icon = "fileText";
    color = "#FB7185";
  } else if (["zip", "rar", "7z", "tar", "gz"].includes(ext)) {
    icon = "archive";
    color = "#FBBF24";
  } else if (ext === "apk") {
    icon = "package";
    color = "#4ADE80";
  } else if (["doc", "docx", "txt", "md", "rtf", "odt", "xls", "xlsx", "ppt", "pptx", "csv"].includes(ext)) {
    icon = "fileText";
    color = "#7DB4FF";
  }
  return (
    <span style={{ color, display: "inline-flex" }}>
      <Icon name={icon} size={size} />
    </span>
  );
}

